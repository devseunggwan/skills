def _wrapper_body(entry: dict) -> str:
    role = entry["role"]
    name = entry["name"]
    if entry.get("body") == "impl.sh":
        return WRAPPER_SH_TEMPLATE.format(role=role, name=name)
    # Python wrapper. If wrapper_suffix is set, bake the dispatch args
    # into the wrapper body so each event leg has its own entry point.
    if entry.get("wrapper_suffix"):
        baked = entry.get("args") or []
        baked_args = "".join(f'"{a}" ' for a in baked)
    else:
        baked_args = ""
    return WRAPPER_PY_TEMPLATE.format(role=role, name=name, baked_args=baked_args)


def _wrapper_registrations(
    manifest: dict,
) -> dict[str, list[tuple[str | None, str | None, bool]]]:
    """Map each wrapper filename to every (event, matcher, has_args) it serves.

    A wrapper file is shared by all manifest entries with the same
    (name, wrapper_suffix), so the registrations must be aggregated ACROSS those
    entries. This is what makes the dispatch-only test correct for a multi-event
    hook: one registered for both Bash and AskUserQuestion still needs its wrapper
    for the (non-dispatched) AskUserQuestion leg, so it is NOT dispatch-only.
    Multi-event hooks are flat sibling entries in the manifest (one object per
    event); the hypothetical nested "entries" form had zero uses and was removed
    (issue #1169).
    """
    regs: dict[str, list[tuple[str | None, str | None, bool]]] = {}
    for entry in manifest["hooks"]:
        fname = _wrapper_filename(entry)
        regs.setdefault(fname, []).append(
            (entry.get("event"), entry.get("matcher"), bool(entry.get("args")))
        )
    return regs


def dispatch_only_wrappers(manifest: dict) -> set[str]:
    """Wrapper filenames whose every registration is collapsed into a dispatch
    group (ADR-0002 Phase 4 / #618).

    These members are invoked only through the single dispatcher
    (`_dispatch.sh`), which imports each member's `impl.py` in-process (or, for
    a `body: impl.sh` member, execs the impl as a subprocess — issue #1281) — so
    the per-member `hooks/<name>.sh` wrapper has no `hooks.json` node
    referencing it and is dead weight. `emit_wrappers` skips them and
    `check-plugin-manifests.py` (Rule 6) asserts they are absent from disk. A
    hook with any non-dispatched registration keeps its wrapper (see
    `_wrapper_registrations`). An args-declaring registration is never
    dispatch-only even inside a dispatch group: the collapse keeps its
    standalone node (see `filter_hooks_for_host`), which still execs the
    wrapper.
    """
    dispatch = frozenset(
        (g["event"], g.get("matcher")) for g in manifest.get("dispatch_groups", [])
    )
    return {
        fname
        for fname, regs in _wrapper_registrations(manifest).items()
        if regs
        and all((ev, ma) in dispatch and not has_args for ev, ma, has_args in regs)
    }


def emit_wrappers(manifest: dict) -> list[str]:
    """Generate hooks/<name>{suffix}.sh wrappers from the manifest +
    the OPT_IN_HOOKS set.

    Returns relative paths that were created or rewritten. Multiple
    manifest entries that share the same (name, wrapper_suffix) emit a
    single wrapper file (e.g. strike-counter is registered for three
    events but only needs one wrapper).
    """
    # ADR-0002 Phase 4 (#618): a member whose every registration is collapsed
    # into a dispatch group is invoked only through _dispatch.sh, so its
    # per-member wrapper is never referenced — skip it.
    skip = dispatch_only_wrappers(manifest)
    emitted: dict[str, str] = {}
    for entry in manifest["hooks"]:
        fname = _wrapper_filename(entry)
        if fname in skip:
            continue
        body = _wrapper_body(entry)
        if fname in emitted:
            if emitted[fname] != body:
                raise SystemExit(
                    f"manifest inconsistency: wrapper '{fname}' would be "
                    f"emitted with two different bodies"
                )
            continue
        emitted[fname] = body

    # Opt-in hooks: not in manifest, but their documented invocation
    # path goes through hooks/<name>.sh, so emit a wrapper anyway.
    for opt_in_name, opt_in_role in OPT_IN_HOOKS.items():
        fname = f"{opt_in_name}.sh"
        if fname in emitted:
            continue  # opt-in name collides with a manifest entry — manifest wins
        body = WRAPPER_PY_TEMPLATE.format(
            role=opt_in_role, name=opt_in_name, baked_args=""
        )
        emitted[fname] = body

    # ADR-0002: the single dispatch-runner wrapper. Dispatch-group hooks.json
    # nodes exec this (with event/matcher/host args) instead of one wrapper per
    # member. Members registered ONLY in a dispatch group no longer get their own
    # wrapper (skipped above, #618); a member also registered for a
    # non-dispatched event/matcher keeps its wrapper for that leg.
    emitted[DISPATCH_WRAPPER_NAME] = WRAPPER_DISPATCH_TEMPLATE

    changed: list[str] = []
    HOOKS_DIR.mkdir(parents=True, exist_ok=True)
    for fname, body in sorted(emitted.items()):
        out_path = HOOKS_DIR / fname
        existing = out_path.read_text() if out_path.exists() else None
        if existing != body:
            out_path.write_text(body)
            os.chmod(out_path, 0o755)
            changed.append(str(out_path.relative_to(REPO_ROOT)))
        else:
            # Ensure executable bit even when content matches.
            st = out_path.stat()
            if not (st.st_mode & 0o111):
                os.chmod(out_path, 0o755)
                changed.append(str(out_path.relative_to(REPO_ROOT)))
    return changed


def hook_identities(manifest: dict) -> dict[str, str]:
    """Map hook name -> role for every hook that owns a directory: manifest
    entries (deduped by name across multi-event registrations) plus the
    OPT_IN_HOOKS set (not in the manifest, but a real hook dir). The single
    source of truth for the per-hook docs/hook stubs (#606) and their
    byte-identity check (check Rule 15).
    """
    ids: dict[str, str] = {}
    for entry in manifest["hooks"]:
        ids[entry["name"]] = entry["role"]
    for name, role in OPT_IN_HOOKS.items():
        ids.setdefault(name, role)
    collisions = set(ids) & NON_HOOK_DOCS
    if collisions:
        raise SystemExit(
            "manifest inconsistency: hook name(s) collide with NON_HOOK_DOCS "
            f"(a hand-written doc would be shadowed by a stub): {sorted(collisions)}"
        )
    return ids


def doc_stub_body(role: str, name: str) -> str:
    """The canonical 1-line redirect stub body for docs/hook/<name>.md."""
    return DOC_STUB_TEMPLATE.format(role=role, name=name)


def emit_doc_stubs(manifest: dict) -> list[str]:
    """Generate docs/hook/<name>.md 1-line redirect stubs, one per hook dir
    (ADR-0001 §337-338, #606). Idempotent: only files whose body differs are
    rewritten. Hand-written docs (NON_HOOK_DOCS, e.g. block-message-format.md)
    are never touched — they are not hook identities.

    Returns relative paths that were created or rewritten.
    """
    changed: list[str] = []
    DOCS_HOOK_DIR.mkdir(parents=True, exist_ok=True)
    for name, role in sorted(hook_identities(manifest).items()):
        out_path = DOCS_HOOK_DIR / f"{name}.md"
        body = doc_stub_body(role, name)
        existing = out_path.read_text() if out_path.exists() else None
        if existing != body:
            out_path.write_text(body)
            changed.append(str(out_path.relative_to(REPO_ROOT)))
    return changed


