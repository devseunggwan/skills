# ---------------------------------------------------------------------------

def main() -> int:
    base = load_base()
    manifest = load_manifest()

    # Schema gate (#1173): the build must refuse to render from a malformed
    # manifest — otherwise a typo'd key is silently absorbed into every
    # generated artifact (and a missing key becomes a KeyError) before
    # check-plugin-manifests.py ever runs the same shared gate.
    schema_drifts = manifest_schema_drifts(manifest)
    if schema_drifts:
        for d in schema_drifts:
            print(f"ERROR {d}", file=sys.stderr)
        return 1

    hooks_source = expand_to_hooks_json(manifest)
    dispatch_groups = frozenset(
        (g["event"], g.get("matcher")) for g in manifest.get("dispatch_groups", [])
    )

    changed_paths: list[str] = []

    for platform_file in sorted(PLATFORMS_DIR.glob("*.json")):
        platform = load_platform(platform_file)
        host_id = platform.get("host_id", platform["platform"])
        for output in platform["outputs"]:
            out_path = REPO_ROOT / output["path"]
            rendered = render_output(base, output, hooks_source, host_id, dispatch_groups)
            if write_json(out_path, rendered):
                changed_paths.append(output["path"])

    # Adapter shell symlinks — Codex plugin forwards to repo-root runtime dirs.
    for name in FORWARDED_DIRS:
        link = ADAPTER_SHELL / name
        target = f"../../{name}"  # relative from plugins/praxis/<name>
        if ensure_symlink(link, target):
            changed_paths.append(str(link.relative_to(REPO_ROOT)))

    # Phase 2: runtime wrappers generated from manifest. These replace the
    # 35 hand-maintained source wrappers deleted in Phase 2 commit 2.
    changed_paths.extend(emit_wrappers(manifest))

    # docs/hook/<name>.md redirect stubs, one per hook dir (ADR-0001 §337-338, #606).
    changed_paths.extend(emit_doc_stubs(manifest))

    # Generated operating-surface matrix for hook owners and users.
    changed_paths.extend(emit_hook_operating_matrix(manifest))

    if changed_paths:
        print("wrote:")
        for p in changed_paths:
            print(f"  {p}")
    else:
        print("clean — no changes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
